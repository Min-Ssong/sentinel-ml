CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID      VARCHAR(36)     NOT NULL,
    USER_ID             VARCHAR(36)     NOT NULL,
    AMOUNT              DECIMAL(15,2)   NOT NULL,
    MERCHANT_CATEGORY   VARCHAR(50)     NOT NULL,
    DEVICE_ID           VARCHAR(100),
    IP_ADDRESS          VARCHAR(45),
    COUNTRY             VARCHAR(100),
    TIMESTAMP           TIMESTAMP       NOT NULL,
    STATUS              VARCHAR(20)     NOT NULL DEFAULT 'PENDING',
    CREATED_AT          TIMESTAMP       NOT NULL DEFAULT NOW(),

    CONSTRAINT PK_TRANSACTION PRIMARY KEY (TRANSACTION_ID)
);

CREATE TABLE MODEL_METADATA (
    ID              BIGSERIAL       NOT NULL,
    MODEL_NAME      VARCHAR(100)    NOT NULL,
    VERSION         VARCHAR(20)     NOT NULL,
    MLFLOW_RUN_ID   VARCHAR(36)     NOT NULL,
    DEPLOYED_AT     TIMESTAMP,
    IS_ACTIVE       BOOLEAN         NOT NULL DEFAULT FALSE,
    CREATED_AT       TIMESTAMP       NOT NULL DEFAULT NOW(),

    CONSTRAINT PK_MODEL_METADATA PRIMARY KEY (ID),
    CONSTRAINT UQ_MODEL_METADATA_NAME_VERSION UNIQUE (MODEL_NAME, VERSION)
);

CREATE TABLE FRAUD_RESULTS (
    ID              BIGSERIAL   NOT NULL,
    TRANSACTION_ID  VARCHAR(36) NOT NULL,
    MODEL_ID        BIGINT      NOT NULL,
    RULE_TRIGGERED  VARCHAR(100),
    ML_SCORE        DECIMAL(5,4),
    FINAL_DECISION  VARCHAR(20) NOT NULL,
    ROLE            VARCHAR(20) NOT NULL,   -- CHAMPION(실제 판정) / CHALLENGER(Shadow, 판정 미사용)
    CREATED_AT      TIMESTAMP   NOT NULL DEFAULT NOW(),

    CONSTRAINT PK_FRAUD_RESULTS PRIMARY KEY (ID),
    CONSTRAINT FK_FRAUD_TRANSACTION FOREIGN KEY (TRANSACTION_ID) REFERENCES TRANSACTIONS(TRANSACTION_ID),
    CONSTRAINT FK_FRAUD_MODEL FOREIGN KEY (MODEL_ID) REFERENCES MODEL_METADATA(ID),
    CONSTRAINT CK_FRAUD_RESULTS_ROLE CHECK (ROLE IN ('CHAMPION', 'CHALLENGER'))
);

CREATE INDEX IX_FRAUD_RESULTS_TRANSACTION ON FRAUD_RESULTS (TRANSACTION_ID);
